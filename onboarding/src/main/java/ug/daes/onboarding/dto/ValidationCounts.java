package ug.daes.onboarding.dto;

public class ValidationCounts {

    int countDevice;
    int countMobile;
    int countEmail;

    public int getCountDevice() {
        return countDevice;
    }

    public void setCountDevice(int countDevice) {
        this.countDevice = countDevice;
    }

    public int getCountMobile() {
        return countMobile;
    }

    public void setCountMobile(int countMobile) {
        this.countMobile = countMobile;
    }

    public int getCountEmail() {
        return countEmail;
    }

    public void setCountEmail(int countEmail) {
        this.countEmail = countEmail;
    }
}